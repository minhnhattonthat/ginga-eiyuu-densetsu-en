def main():
    assert len(GLYPHS) == 0x1FF, hex(len(GLYPHS))
    assert len(set(GLYPHS)) == len(GLYPHS), [c for c in set(GLYPHS) if GLYPHS.count(c) > 1]
    out = ["# jp.tbl: generated by tools/mk_jp_tbl.py, do not edit by hand"]
    for g, ch in enumerate(GLYPHS):
        if g < 0xD0:
            key = "%02X" % g
        else:
            hi, lo = divmod(g - 0xD0, 0x100)
            key = "%02X%02X" % (0xD0 + hi, lo)
        out.append(f"{key}={ch}")
    out.append(CTRL.rstrip("\n"))
    p = ROOT / "tbl" / "jp.tbl"
    p.parent.mkdir(exist_ok=True)
    p.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {p} ({len(GLYPHS)} glyphs)")


if __name__ == "__main__":
    main()
